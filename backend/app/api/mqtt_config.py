class PreflightCheck(BaseModel):
    id: str
    label: str
    # ok = verified good, fail = verified bad, unknown = we could not tell
    state: str
    detail: str
    fix: str | None = None


@router.get("/preflight/{camera_id}", response_model=list[PreflightCheck])
async def preflight(
    camera_id: str,
    connection_id: UUID | None = Query(default=None),
    session: AsyncSession = Depends(get_session),
) -> list[PreflightCheck]:
    """Everything that has to be true before a camera will publish.

    Each of these has cost somebody an afternoon at least once. The
    occupancy-trends line is the worst of them: without it the camera
    connects, authenticates, and publishes nothing at all, which looks
    identical to a broken broker.
    """
    checks: list[PreflightCheck] = []

    checks.append(
        PreflightCheck(
            id="ca",
            label="Broker certificate generated",
            state="ok" if CA_PATH.is_file() else "fail",
            detail=(
                "root_ca.pem is present and will be pushed to the camera."
                if CA_PATH.is_file()
                else "No CA found at mqtt/certs/root_ca.pem."
            ),
            fix=None if CA_PATH.is_file() else "Run ./mqtt/gen-certs.sh <broker-address> on the host.",
        )
    )

    checks.append(
        PreflightCheck(
            id="ingest",
            label="Broker reachable from vFusion",
            state="ok" if ingest.connected else "fail",
            detail=(
                "Subscribed to the ingest broker."
                if ingest.connected
                else f"Not connected: {ingest.last_error or 'ingest disabled'}"
            ),
            # detail already carries the specific command when we know
            # what went wrong; a generic fix underneath it just competes.
            fix=(
                None
                if ingest.connected or ingest.last_error
                else "Start the broker: docker compose --profile mqtt up -d"
            ),
        )
    )

    cam = (
        await session.execute(
            select(VerkadaCamera).where(VerkadaCamera.camera_id == camera_id)
        )
    ).scalars().first()

    if cam is None:
        checks.append(
            PreflightCheck(
                id="camera",
                label="Camera known",
                state="unknown",
                detail="Camera is not in the local cache.",
                fix="Sync cameras on the Connections page.",
            )
        )
        return checks

    online = bool(cam.status) and cam.status.lower() != "offline"
    checks.append(
        PreflightCheck(
            id="online",
            label="Camera online",
            state="ok" if online else "fail",
            detail=f"Status is {cam.status or 'unknown'}.",
            fix=None if online else "An offline camera cannot be configured or publish.",
        )
    )

    raw = cam.raw if isinstance(cam.raw, dict) else {}
    people = raw.get("people_history_enabled")
    checks.append(
        PreflightCheck(
            id="analytics",
            label="People analytics enabled",
            state="ok" if people else ("fail" if people is False else "unknown"),
            detail=f"people_history_enabled is {people!r}.",
            fix=None if people else "Enable People History on the camera in Command.",
        )
    )

    # The occupancy-trends line. There is no API to draw one, so the most
    # this can do is tell the operator to go draw it.
    checks.append(await _occupancy_check(session, camera_id, connection_id))
    checks.append(await _existing_config_check(session, camera_id, connection_id))
    return checks


def _normalise_pem(text: str) -> str:
    """Compare certificates by content, ignoring line-ending noise."""
    return "".join(str(text or "").split())


async def _existing_config_check(
    session: AsyncSession, camera_id: str, connection_id: UUID | None
) -> PreflightCheck:
    """Whether this camera is already pointed here, with the current cert.

    Without this the page looks identical for a camera that was
    configured months ago and one that has never been touched, so the
    only way to find out is to push again — and a push rotates nothing
    but does churn the camera's connection for 5-25 seconds.

    The certificate matters as much as the address: after regenerating,
    every camera still holds the old CA and will fail the handshake
    while looking perfectly configured.
    """
    unknown = PreflightCheck(
        id="pushed",
        label="Already pointed at this broker",
        state="unknown",
        detail="Could not read the camera's current config.",
    )
    client = await _client_for(session, connection_id)
    if client is None:
        unknown.detail = "No Verkada connection is set up."
        return unknown
    try:
        config = await client.get_object_position_mqtt_config(camera_id)
    except VerkadaApiError as e:
        unknown.detail = _permission_hint(e)
        return unknown

    host_port = str(config.get("broker_host_port") or "")
    if not host_port:
        return PreflightCheck(
            id="pushed",
            label="Already pointed at this broker",
            state="fail",
            detail="Not configured yet — this camera has no broker set.",
            fix="Push the config below.",
        )

    expected = broker_mode.camera_target()["broker_host_port"]
    if expected and host_port != expected:
        return PreflightCheck(
            id="pushed",
            label="Already pointed at this broker",
            state="fail",
            detail=f"Pointed at {host_port} rather than {expected}.",
            fix="Push the config below to move it here.",
        )

    ca = broker_mode.camera_target()["broker_cert"]
    if ca and _normalise_pem(config.get("broker_cert", "")) != _normalise_pem(ca):
        return PreflightCheck(
            id="pushed",
            label="Already pointed at this broker",
            state="fail",
            detail=(
                f"Set to {host_port}, but holding a different certificate than "
                "the one generated here — the TLS handshake will fail."
            ),
            fix="Push the config below to send the current certificate.",
        )

    return PreflightCheck(
        id="pushed",
        label="Already pointed at this broker",
        state="ok",
        detail=(
            f"Configured for {host_port} as "
            f"{config.get('client_username') or 'unknown user'}, with the current "
            "certificate. No need to push again."
        ),
    )


async def _occupancy_check(
    session: AsyncSession, camera_id: str, connection_id: UUID | None
) -> PreflightCheck:
    unknown = PreflightCheck(
        id="line",
        label="Occupancy Trends line drawn",
        state="unknown",
        detail="Could not verify.",
        fix=(
            "Command → Camera → Analytics → Occupancy Trends → Edit Lines. "
            "Without a line the camera connects but never publishes."
        ),
    )
    client = await _client_for(session, connection_id)
    if client is None:
        unknown.detail = "No Verkada connection is set up."
        return unknown
    try:
        cameras = await client.list_occupancy_trend_cameras()
    except VerkadaApiError as e:
        if e.status_code == 403:
            unknown.detail = (
                "Verkada returned 403 reading occupancy trends. That can mean the "
                "key lacks the scope, but Verkada also answers unknown paths with "
                "403 — the line itself may well be fine."
            )
        else:
            unknown.detail = f"Lookup failed: {e}"
        return unknown

    hit = next(
        (c for c in cameras if isinstance(c, dict) and c.get("camera_id") == camera_id),
        None,
    )
    presets = (hit or {}).get("preset_ids") or []
    if hit and presets:
        classes = sorted(
            {
                p.get("object_class")
                for p in (hit.get("presets") or [])
                if isinstance(p, dict) and p.get("object_class")
            }
        )
        detail = f"{len(presets)} line preset(s) configured."
        if classes:
            detail += (
                f" Tracking {', '.join(classes)} — a class with no line "
                "drawn for it will not be reported."
            )
        return PreflightCheck(
            id="line", label="Occupancy Trends line drawn", state="ok", detail=detail
        )
    return PreflightCheck(
        id="line",
        label="Occupancy Trends line drawn",
        state="fail",
        detail="No line preset on this camera — it will connect but never publish.",
        fix="Command → Camera → Analytics → Occupancy Trends → Edit Lines.",
    )


async def _client_for(
    session: AsyncSession, connection_id: UUID | None
) -> VerkadaClient | None:
    q = select(Connection).where(Connection.type == "verkada")
    if connection_id:
        q = q.where(Connection.id == connection_id)
    conn = (await session.execute(q)).scalars().first()
    if conn is None:
        return None
    try:
        secret = decrypt_secret(conn.encrypted_secret)
    except Exception:
        return None
    api_key = secret.get("api_key")
    if not api_key:
        return None
    return VerkadaClient(api_key=api_key, base_url=secret.get("region") or None)


