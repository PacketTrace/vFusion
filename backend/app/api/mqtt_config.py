async def _stream_context(
    session: AsyncSession, connection_id: UUID | None
) -> tuple[str, str, str]:
    """(base_url, org_id, jwt) for the live HLS stream."""
    q = select(Connection).where(Connection.type == "verkada")
    if connection_id:
        q = q.where(Connection.id == connection_id)
    conn = (await session.execute(q)).scalars().first()
    if conn is None:
        raise HTTPException(status_code=400, detail="no Verkada connection configured")
    try:
        secret = decrypt_secret(conn.encrypted_secret)
    except Exception as e:
        raise HTTPException(status_code=400, detail="could not decrypt connection") from e
    api_key = secret.get("api_key")
    org_id = conn.external_id
    if not api_key or not org_id:
        raise HTTPException(
            status_code=400, detail="connection is missing an API key or org id"
        )
    base = (secret.get("region") or "https://api.verkada.com").rstrip("/")
    try:
        jwt = await get_stream_key(api_key, org_id, base_url=base)
    except FootageError as e:
        raise HTTPException(status_code=400, detail=str(e)) from e
    return base, org_id, jwt


def _stream_query(org_id: str, camera_id: str, jwt: str) -> dict[str, str]:
    """Query for the live HLS stream.

    low_res, not high_res, and the reason is the whole feature: Verkada
    serves high_res as HEVC and low_res as H.264. No transcode flag
    changes that -- transcode=true still returns hevc at high_res. HEVC
    is why nothing rendered: Chrome downloaded segments and decoded
    nothing, and the codebase's existing consumers all run the stream
    through ffmpeg, which decodes it happily and hid the problem.

    low_res also happens to publish three segments rather than two,
    which satisfies the three-target-durations rule Safari enforces
    before it will start a live stream.

    Resolution costs nothing here: the boxes are normalised coordinates
    and scale to whatever size the video renders at.
    """
    return {
        "org_id": org_id,
        "camera_id": camera_id,
        "resolution": "low_res",
        "type": "stream",
        "codec": "h264",
        "transcode": "false",
        "start_time": "0",
        "end_time": "0",
        "jwt": jwt,
    }


@router.get("/stream/{camera_id}/index.m3u8")
async def stream_playlist(
    camera_id: str,
    connection_id: UUID | None = Query(default=None),
    session: AsyncSession = Depends(get_session),
) -> Response:
    """Live HLS playlist with the credentials stripped out.

    Every segment URI upstream carries a signed JWT, so handing the
    playlist straight to a browser would publish a working stream
    credential into the DOM and the network log. This rewrites each URI
    to a path on this server and keeps the token here; the proxy rebuilds
    the real query when fetching a segment.
    """
    base, org_id, jwt = await _stream_context(session, connection_id)
    async with httpx.AsyncClient(timeout=20.0) as client:
        res = await client.get(
            f"{base}{STREAM_BASE}/stream.m3u8",
            params=_stream_query(org_id, camera_id, jwt),
        )
    if res.status_code != 200:
        raise HTTPException(
            status_code=502, detail=f"stream playlist failed: HTTP {res.status_code}"
        )

    header: list[str] = []
    fresh: list[tuple[str, list[str]]] = []
    pending: list[str] = []
    upstream_seq = 0
    for line in res.text.splitlines():
        if line.startswith("#EXT-X-MAP:"):
            m = re.search(r'URI="([^"?]+)', line)
            if m:
                header.append(f'#EXT-X-MAP:URI="seg/{m.group(1)}"')
            continue
        if line.startswith("#EXT-X-MEDIA-SEQUENCE:"):
            try:
                upstream_seq = int(line.split(":", 1)[1])
            except ValueError:
                upstream_seq = 0
            continue
        if line.startswith("#EXTINF") or line.startswith("#EXT-X-PROGRAM-DATE-TIME"):
            pending.append(line)
            continue
        if line.startswith("#"):
            header.append(line)
            continue
        if line:
            fresh.append((line.split("?", 1)[0], pending))
            pending = []

    window = _WINDOW.setdefault(camera_id, deque(maxlen=_WINDOW_SEGMENTS))
    known = {name for name, _ in window}
    for name, tags in fresh:
        if name not in known:
            window.append((name, tags))

    names = [name for name, _ in window]
    # MEDIA-SEQUENCE must number the first segment we publish, which is
    # older than the first one upstream is currently advertising.
    older = 0
    if fresh:
        first_upstream = fresh[0][0]
        older = names.index(first_upstream) if first_upstream in names else 0
    body = header + [f"#EXT-X-MEDIA-SEQUENCE:{max(0, upstream_seq - older)}"]
    for name, tags in window:
        body.extend(tags)
        body.append(f"seg/{name}")

    return Response(
        content="\n".join(body) + "\n",
        media_type="application/vnd.apple.mpegurl",
        headers={"Cache-Control": "no-store"},
    )


# Recently fetched segments, so a range probe followed by the real read
# does not pull the same ~700 KB twice. Small on purpose: this is a live
# stream, and anything more than a few seconds back is never asked for.
_SEG_CACHE: "OrderedDict[str, bytes]" = OrderedDict()
_SEG_CACHE_MAX = 8


def _parse_range(header: str, size: int) -> tuple[int, int] | None:
    """Resolve a single-range header to inclusive (start, end) offsets."""
    if not header.startswith("bytes="):
        return None
    spec = header[6:].split(",", 1)[0].strip()
    try:
        if spec.startswith("-"):
            length = int(spec[1:])
            if length <= 0:
                return None
            return max(0, size - length), size - 1
        first, _, last = spec.partition("-")
        begin = int(first)
        finish = int(last) if last else size - 1
    except ValueError:
        return None
    finish = min(finish, size - 1)
    if begin > finish or begin >= size:
        return None
    return begin, finish


@router.get("/stream/{camera_id}/seg/{name}")
async def stream_segment(
    camera_id: str,
    name: str,
    request: Request,
    connection_id: UUID | None = Query(default=None),
    session: AsyncSession = Depends(get_session),
) -> Response:
    """Proxy one media segment, re-attaching the credentials server-side.

    Ranges are satisfied here rather than upstream, because Verkada
    ignores the header and answers every request with the whole object.
    Forwarding it and passing the 200 back meant advertising range
    support we did not provide -- which is worse than not advertising it:
    hls.js does not care, but Safari's native player probes with a Range,
    expects a 206, and on getting a 200 fetches the init segment and then
    silently stops asking for media.
    """
    if not _SEGMENT_RE.match(name):
        raise HTTPException(status_code=400, detail="bad segment name")

    key = f"{camera_id}/{name}"
    cached = _SEG_CACHE.get(key)
    if cached is None:
        base, org_id, jwt = await _stream_context(session, connection_id)
        async with httpx.AsyncClient(timeout=30.0) as client:
            res = await client.get(
                f"{base}{STREAM_BASE}/{name}",
                params=_stream_query(org_id, camera_id, jwt),
            )
        if res.status_code != 200:
            raise HTTPException(
                status_code=502, detail=f"segment failed: HTTP {res.status_code}"
            )
        cached = res.content
        _SEG_CACHE[key] = cached
        while len(_SEG_CACHE) > _SEG_CACHE_MAX:
            _SEG_CACHE.popitem(last=False)
    else:
        _SEG_CACHE.move_to_end(key)

    size = len(cached)
    headers = {
        "Cache-Control": "no-store",
        "Accept-Ranges": "bytes",
    }
    rng = request.headers.get("range")
    if rng:
        span = _parse_range(rng, size)
        if span is None:
            return Response(
                status_code=416,
                headers={**headers, "Content-Range": f"bytes */{size}"},
            )
        begin, finish = span
        body = cached[begin : finish + 1]
        headers["Content-Range"] = f"bytes {begin}-{finish}/{size}"
        return Response(
            content=body,
            status_code=206,
            media_type="video/mp4",
            headers=headers,
        )

    return Response(
        content=cached,
        media_type="video/mp4",
        headers=headers,
    )


