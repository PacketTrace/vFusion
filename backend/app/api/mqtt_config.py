@router.post("/config/{camera_id}")
async def set_config(
    camera_id: str,
    body: ConfigureRequest,
    dry_run: bool = Query(default=False, description="Show the request without sending it"),
    session: AsyncSession = Depends(get_session),
) -> dict[str, Any]:
    """Point a camera at this broker, then read it back to prove it stuck.

    The read-back is not defensive padding. The API returns 200 and
    silently discards the config if either credential is missing, so the
    only way to know it took is to ask.
    """
    host_port = broker_mode.camera_target()["broker_host_port"]
    _, _, port = host_port.rpartition(":")
    if port not in ALLOWED_PORTS:
        raise HTTPException(
            status_code=400,
            detail=(
                f"Broker port {port or '(none)'} is not usable — Verkada only "
                "accepts 443, 123 or 53."
            ),
        )
    # Built in: generated certificate and stored credentials. External:
    # whatever was entered, because vFusion cannot derive either.
    target = broker_mode.camera_target()
    missing = [
        name
        for name, value in (
            ("broker address", target["broker_host_port"]),
            ("username", target["client_username"]),
            ("password", target["client_password"]),
            ("broker certificate", target["broker_cert"]),
        )
        if not value
    ]
    if missing:
        raise HTTPException(
            status_code=400,
            detail=(
                "Broker setup is incomplete — missing "
                + ", ".join(missing)
                + ". Finish step 0 first."
            ),
        )
    creds = {
        "username": target["client_username"],
        "password": target["client_password"],
    }

    client = await _client_for(session, body.connection_id)
    if client is None:
        raise HTTPException(status_code=400, detail="no Verkada connection configured")

    ca = target["broker_cert"]
    preview = _request_preview(camera_id, target["broker_host_port"], creds, ca)
    if dry_run:
        return {"dry_run": True, "request": preview}

    try:
        await client.set_object_position_mqtt_config(
            camera_id=camera_id,
            broker_host_port=target["broker_host_port"],
            client_username=creds["username"],
            client_password=creds["password"],
            broker_cert=ca,
        )
    except VerkadaApiError as e:
        # Hand back the request alongside the error: "insufficient
        # permissions" on an endpoint the operator has rights to is
        # almost always a malformed request, and guessing which is
        # which without seeing it wastes an afternoon.
        raise HTTPException(
            status_code=400,
            detail={"error": _permission_hint(e), "request": preview},
        ) from e

    # Read back separately: the write is what matters, and a failure to
    # confirm it is not a failure to do it. Conflating the two reported
    # a successful push as a permissions error.
    readback: dict[str, Any] = {}
    readback_error: str | None = None
    try:
        readback = await client.get_object_position_mqtt_config(camera_id)
    except VerkadaApiError as e:
        readback_error = f"Config was sent, but reading it back failed: {e}"

    persisted = bool(readback.get("broker_host_port")) and bool(
        readback.get("client_username")
    )
    return {
        "persisted": persisted,
        "config": readback,
        "request": preview,
        "readback_error": readback_error,
        "note": (
            "Camera reconnects within ~5–25s of a config change."
            if persisted
            else readback_error
            or "Verkada accepted the call but stored nothing — re-send with both credentials."
        ),
    }


def _request_preview(
    camera_id: str, broker_host_port: str, creds: dict[str, str], ca: str
) -> dict[str, Any]:
    """Exactly what we send Verkada, with the secrets rendered inert.

    A 403 from an endpoint you believe you have rights to is usually the
    request being wrong rather than the key, and there is no way to tell
    those apart without seeing what actually went out. The API key never
    appears -- not even partially -- because this is meant to be
    screenshot-able.
    """
    ca_lines = ca.strip().splitlines()
    return {
        "method": "POST",
        "url": "https://api.verkada.com/cameras/v1/analytics/object_position_mqtt",
        "headers": {
            "x-verkada-auth": "<token minted from the connection's API key>",
            "content-type": "application/json",
        },
        "body": {
            "camera_id": camera_id,
            "broker_host_port": broker_host_port,
            "client_username": creds["username"],
            "client_password": f"<{len(creds['password'])} chars>",
            "broker_cert": (
                f"{ca_lines[0] if ca_lines else ''} … "
                f"{len(ca_lines)} lines, {len(ca)} chars"
            ),
        },
        "notes": [
            "Auth is a short-lived token from POST /token, not the API key itself.",
            "Both credentials must be present or Verkada 200s and stores nothing.",
            "broker_cert must be the CA, not the server leaf.",
        ],
    }


def _permission_hint(e: VerkadaApiError) -> str:
    if e.status_code == 403:
        # Verkada returns this for an unknown path as well as a genuine
        # scope problem, so do not assert which one it is.
        return (
            "Verkada returned 403. That usually means the API key lacks read/write "
            "access to Cameras, but Verkada also answers unknown paths with 403, "
            "so check the request above before changing key permissions."
        )
    if e.status_code == 401:
        return "Verkada rejected the API key (401)."
    return str(e)


class SetupRequest(BaseModel):
    broker_host: str
    username: str = "vfusion"
    # Omit to have one generated -- it is only ever typed by a camera.
    password: str | None = None
    # Existing credentials are reused by default. Changing them requires
    # restarting mosquitto, which vFusion cannot do, so it should be a
    # thing you asked for rather than a side effect of regenerating certs.
    rotate_password: bool = False


@router.post("/setup")
async def setup(body: SetupRequest) -> dict[str, Any]:
    """Generate the broker's certificate and credentials.

    Everything here used to be a shell script run on the docker host. The
    address matters more than it looks: it is baked into the certificate's
    SAN, so changing it later invalidates every camera already pointed
    here and means re-pushing all of them.
    """
    host = body.broker_host.strip()
    if ":" in host and not host.startswith("["):
        # Easy mistake, since the camera field does want host:port.
        raise HTTPException(
            status_code=400,
            detail="Enter the host or IP only — the port is always 443 here.",
        )
    if not host:
        raise HTTPException(status_code=400, detail="broker_host is required")

    existing = provision.load_credentials()
    reuse = existing is not None and not body.rotate_password and body.password is None
    password = (
        existing["password"] if reuse and existing else (body.password or provision.generate_password())
    )
    username = existing["username"] if reuse and existing else body.username
    try:
        info = provision.generate_certs(host)
        if not reuse:
            # Only touch the password file when the password actually
            # changes: mosquitto reads it once at startup, so rewriting it
            # under a running broker locks out the very credentials this
            # process is about to use.
            provision.write_password_file(username, password)
            provision.save_credentials(username, password)
    except OSError as e:
        raise HTTPException(
            status_code=500,
            detail=f"Could not write to {provision.MQTT_DIR}: {e}",
        ) from e

    await ingest.restart()
    restart_needed = ["mqtt-tls"] + ([] if reuse else ["mqtt-broker"])
    return {
        "broker_host_port": f"{host}:443",
        "username": username,
        "password_rotated": not reuse,
        "san": info["san"],
        "expires": info["expires"],
        # Deliberately no password here. It is stored encrypted and used
        # directly when configuring a camera, so there is nothing for the
        # operator to write down and nothing to lose by closing the tab.
        "next_steps": [
            "Start the broker:  docker compose --profile mqtt up -d",
            "Already running?  docker compose restart " + " ".join(restart_needed)
            + ("  (mosquitto only reads its password file at startup)" if not reuse
               else "  (nginx only reads certificates at startup)"),
        ],
    }


@router.delete("/config/{camera_id}")
async def clear_config(
    camera_id: str,
    connection_id: UUID | None = Query(default=None),
    session: AsyncSession = Depends(get_session),
) -> dict[str, Any]:
    """Unpoint a camera from its broker.

    Also the documented way to force a reconnect: the camera only acts on
    a config *change*, so re-pushing identical settings may do nothing
    while clear-then-set reliably brings it back within ~5-25s.
    """
    client = await _client_for(session, connection_id)
    if client is None:
        raise HTTPException(status_code=400, detail="no Verkada connection configured")
    try:
        await client.set_object_position_mqtt_config(
            camera_id=camera_id,
            broker_host_port="",
            client_username="",
            client_password="",
            broker_cert="",
        )
    except VerkadaApiError as e:
        raise HTTPException(status_code=400, detail=_permission_hint(e)) from e
    return {"cleared": True}


@router.post("/reset")
async def reset() -> dict[str, Any]:
    """Delete the generated certificate, password file and credentials.

    For starting over after the broker address changes -- the address is
    baked into the certificate SAN, so a move invalidates everything and
    every camera has to be re-pushed anyway.
    """
    removed = provision.clear()
    await ingest.restart()
    return {
        "removed": removed,
        "note": (
            "Cameras still point here until re-pushed. "
            "Restart mqtt-broker and mqtt-tls after generating again."
        ),
    }


# Segment names in the upstream playlist. Anchored so the proxy can only
# ever be pointed at Verkada's own stream files, never an arbitrary URL.
_SEGMENT_RE = re.compile(r"^[A-Za-z0-9_.-]+\.(m4s|mp4|ts)$")

STREAM_BASE = "/stream/cameras/v1/footage/stream"

# Upstream publishes a two-segment window -- eight seconds against a
# four-second target duration. Apple's spec says a client should not start
# playback until a live playlist holds three target durations, so Safari
# fetches the init segment and then reloads the playlist forever without
# ever requesting media. hls.js ignores the rule and plays, which is why
# this looked like a Safari-only codec problem.
#
# So remember the segments we have already seen and republish a longer
# window. The names stay valid upstream for a while, and anything we
# served recently is still in the segment cache.
_WINDOW: "dict[str, deque]" = {}
_WINDOW_SEGMENTS = 6


